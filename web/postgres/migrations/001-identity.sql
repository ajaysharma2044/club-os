-- PostgreSQL schema port of the CEC SQLite schema, including relationship guards.
CREATE TABLE "accounts"(id TEXT PRIMARY KEY,name TEXT NOT NULL,email TEXT UNIQUE NOT NULL,password TEXT NOT NULL,interests TEXT NOT NULL DEFAULT '',shared BIGINT NOT NULL DEFAULT 0);
CREATE TABLE sessions(token TEXT PRIMARY KEY,user_id TEXT REFERENCES "accounts"(id) ON DELETE CASCADE,expires BIGINT NOT NULL);
CREATE TABLE applications(user_id TEXT PRIMARY KEY REFERENCES "accounts"(id),track TEXT NOT NULL,statement TEXT NOT NULL,url TEXT NOT NULL,stage TEXT NOT NULL DEFAULT 'submitted',review TEXT NOT NULL DEFAULT '',created_at TEXT NOT NULL, organization_id TEXT NOT NULL DEFAULT 'cornell-ec' CHECK(organization_id='cornell-ec'));
CREATE TABLE messages(id TEXT PRIMARY KEY,user_id TEXT REFERENCES "accounts"(id),channel TEXT NOT NULL,body TEXT NOT NULL,created_at TEXT NOT NULL, organization_id TEXT NOT NULL DEFAULT 'cornell-ec' CHECK(organization_id='cornell-ec'));
CREATE TABLE audit(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id TEXT UNIQUE NOT NULL,actor TEXT NOT NULL,action TEXT NOT NULL,object_id TEXT NOT NULL,at TEXT NOT NULL,details TEXT NOT NULL, organization_id TEXT NOT NULL DEFAULT 'cornell-ec' CHECK(organization_id='cornell-ec'));
CREATE TABLE outbox(id TEXT PRIMARY KEY,body TEXT NOT NULL,delivered BIGINT NOT NULL DEFAULT 0,error TEXT NOT NULL DEFAULT '', organization_id TEXT NOT NULL DEFAULT 'cornell-ec' CHECK(organization_id='cornell-ec'));
CREATE TABLE ratelimits(key TEXT PRIMARY KEY,hits BIGINT NOT NULL,reset BIGINT NOT NULL);
CREATE TABLE settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE schema_migrations(version BIGINT PRIMARY KEY, applied_at TEXT NOT NULL);
CREATE TABLE organizations(
        id TEXT PRIMARY KEY, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
        status TEXT NOT NULL CHECK(status IN ('active','inactive')),
        created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')));
CREATE TABLE memberships(
        organization_id TEXT NOT NULL REFERENCES organizations(id),
        user_id TEXT NOT NULL REFERENCES accounts(id),
        role TEXT NOT NULL CHECK(role IN ('applicant','member','officer')),
        status TEXT NOT NULL CHECK(status IN ('pending','active','left','suspended')),
        joined_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
        left_at TEXT, version BIGINT NOT NULL DEFAULT 1,
        PRIMARY KEY(organization_id,user_id),
        CHECK((status='pending' AND role='applicant') OR status!='pending'));
CREATE TABLE account_email(user_id TEXT PRIMARY KEY REFERENCES accounts(id),email TEXT NOT NULL,verified_at TEXT,task_notifications BIGINT NOT NULL DEFAULT 1 CHECK(task_notifications IN(0,1)));
CREATE TABLE email_tokens(hash TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES accounts(id),email TEXT NOT NULL,purpose TEXT NOT NULL CHECK(purpose IN('verify','reset')),expires BIGINT NOT NULL,used BIGINT NOT NULL DEFAULT 0);
CREATE TABLE email_jobs(id TEXT PRIMARY KEY,dedupe TEXT NOT NULL UNIQUE,organization_id TEXT NOT NULL DEFAULT 'cornell-ec' CHECK(organization_id='cornell-ec'),kind TEXT NOT NULL,user_id TEXT REFERENCES accounts(id),object_id TEXT NOT NULL DEFAULT '',token_hash TEXT REFERENCES email_tokens(hash),mode TEXT NOT NULL CHECK(mode IN('capture','resend')),payload TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'queued',created BIGINT NOT NULL,expires BIGINT NOT NULL,attempts BIGINT NOT NULL DEFAULT 0,next_attempt BIGINT NOT NULL DEFAULT 0,first_attempt BIGINT,lease TEXT,lease_until BIGINT NOT NULL DEFAULT 0,provider_id TEXT NOT NULL DEFAULT '',error TEXT NOT NULL DEFAULT '');
CREATE TABLE organization_tables(
